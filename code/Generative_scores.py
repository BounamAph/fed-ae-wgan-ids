"""
Generative_scores.py
=====================
Evaluation metrics for the quality of synthetic attacks generated by AE-WGAN.

Based on: Arafah et al. (2025), Applied Soft Computing, 168, 112455.

Metrics:
    1. Cosine Similarity — measures directional similarity between 
       original and generated distributions.
    2. Maximum Mean Discrepancy (MMD) — measures the distance between
       two distributions in a reproducing kernel Hilbert space.
    3. Binary Discrimination Test — trains a classifier to distinguish
       real vs. synthetic; accuracy ~50% = high quality.

Usage:
    from Generative_scores import evaluate_generation_quality
    report = evaluate_generation_quality(X_real, X_synthetic, attack_name="neptune")
"""

import numpy as np
from sklearn.metrics.pairwise import cosine_similarity
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score
import warnings
warnings.filterwarnings('ignore')


def compute_cosine_similarity(X_real, X_synthetic):
    """
    Compute cosine similarity between real and synthetic distributions.
    
    Paper reference: "Cosine similarity is used to measure the distance 
    between original and generated distributions."
    
    A higher value indicates more similarity (higher quality).
    
    Parameters
    ----------
    X_real : np.ndarray
        Real attack samples (N_real, n_features).
    X_synthetic : np.ndarray
        Generated attack samples (N_synth, n_features).
    
    Returns
    -------
    avg_similarity : float
        Average cosine similarity score.
    per_feature_similarity : np.ndarray
        Per-feature mean cosine similarity.
    """
    # Mean vector similarity
    real_mean = X_real.mean(axis=0).reshape(1, -1)
    synth_mean = X_synthetic.mean(axis=0).reshape(1, -1)
    
    mean_similarity = cosine_similarity(real_mean, synth_mean)[0, 0]
    
    # Sample-level: average pairwise cosine similarity
    # For efficiency, sample up to 1000 from each
    n_sample = min(1000, len(X_real), len(X_synthetic))
    idx_real = np.random.choice(len(X_real), n_sample, replace=True)
    idx_synth = np.random.choice(len(X_synthetic), n_sample, replace=True)
    
    sim_matrix = cosine_similarity(X_real[idx_real], X_synthetic[idx_synth])
    avg_pairwise = np.mean(sim_matrix)
    
    return {
        'mean_vector_similarity': float(mean_similarity),
        'avg_pairwise_similarity': float(avg_pairwise),
    }


def compute_mmd(X_real, X_synthetic, kernel='rbf', gamma=None):
    """
    Compute Maximum Mean Discrepancy (MMD) between two distributions.
    
    MMD = ||mu_p - mu_q||^2_H where H is an RKHS.
    Lower MMD = distributions are more similar = higher quality.
    
    Parameters
    ----------
    X_real : np.ndarray
        Real samples.
    X_synthetic : np.ndarray
        Synthetic samples.
    kernel : str
        Kernel type ('rbf' or 'linear').
    gamma : float, optional
        RBF kernel bandwidth. If None, uses median heuristic.
    
    Returns
    -------
    mmd_value : float
        MMD^2 statistic.
    """
    # Subsample for efficiency
    n_sample = min(1000, len(X_real), len(X_synthetic))
    X = X_real[np.random.choice(len(X_real), n_sample, replace=True)]
    Y = X_synthetic[np.random.choice(len(X_synthetic), n_sample, replace=True)]
    
    if kernel == 'linear':
        # Linear kernel MMD
        XX = np.dot(X, X.T)
        YY = np.dot(Y, Y.T)
        XY = np.dot(X, Y.T)
    elif kernel == 'rbf':
        if gamma is None:
            # Median heuristic for bandwidth
            from scipy.spatial.distance import cdist
            dists = cdist(X, Y, 'sqeuclidean')
            gamma = 1.0 / (2.0 * np.median(dists) + 1e-8)
        
        XX = _rbf_kernel(X, X, gamma)
        YY = _rbf_kernel(Y, Y, gamma)
        XY = _rbf_kernel(X, Y, gamma)
    else:
        raise ValueError(f"Unknown kernel: {kernel}")
    
    n = XX.shape[0]
    m = YY.shape[0]
    
    # MMD^2 = E[k(x,x')] + E[k(y,y')] - 2*E[k(x,y)]
    mmd_sq = (np.sum(XX) - np.trace(XX)) / (n * (n - 1)) + \
             (np.sum(YY) - np.trace(YY)) / (m * (m - 1)) - \
             2.0 * np.mean(XY)
    
    return float(max(0, mmd_sq))


def _rbf_kernel(X, Y, gamma):
    """Compute RBF (Gaussian) kernel matrix."""
    from scipy.spatial.distance import cdist
    dists = cdist(X, Y, 'sqeuclidean')
    return np.exp(-gamma * dists)


def binary_discrimination_test(X_real, X_synthetic, n_estimators=100):
    """
    Train a classifier to discriminate real vs. synthetic samples.
    
    Paper reference: "Binary classification is conducted on adversarial 
    and original attacks, where the original attacks were labelled as ones, 
    and the adversarial attacks were labelled as zeros."
    
    Accuracy close to 50% = classifier cannot distinguish them = high quality.
    
    Parameters
    ----------
    X_real : np.ndarray
        Real samples.
    X_synthetic : np.ndarray
        Synthetic samples.
    n_estimators : int
        Number of trees in the Random Forest.
    
    Returns
    -------
    accuracy : float
        Classification accuracy. ~50% is ideal.
    """
    # Balance the dataset
    n = min(len(X_real), len(X_synthetic))
    X_r = X_real[np.random.choice(len(X_real), n, replace=False if n <= len(X_real) else True)]
    X_s = X_synthetic[np.random.choice(len(X_synthetic), n, replace=False if n <= len(X_synthetic) else True)]
    
    X_combined = np.vstack([X_r, X_s])
    y_combined = np.array([1] * n + [0] * n)
    
    X_tr, X_te, y_tr, y_te = train_test_split(
        X_combined, y_combined, test_size=0.3, random_state=42, stratify=y_combined
    )
    
    clf = RandomForestClassifier(n_estimators=n_estimators, random_state=42, n_jobs=-1)
    clf.fit(X_tr, y_tr)
    y_pred = clf.predict(X_te)
    
    return float(accuracy_score(y_te, y_pred))


def compute_statistical_similarity(X_real, X_synthetic):
    """
    Compute basic statistical similarity between distributions.
    
    Compares mean, std, min, max per feature.
    
    Returns
    -------
    stats : dict
        Dictionary with mean/std absolute differences.
    """
    mean_diff = np.mean(np.abs(X_real.mean(axis=0) - X_synthetic.mean(axis=0)))
    std_diff = np.mean(np.abs(X_real.std(axis=0) - X_synthetic.std(axis=0)))
    
    return {
        'mean_absolute_difference': float(mean_diff),
        'std_absolute_difference': float(std_diff),
    }


def evaluate_generation_quality(X_real, X_synthetic, attack_name="attack", verbose=True):
    """
    Full evaluation of generated attack quality.
    
    Computes all metrics: Cosine Similarity, MMD, Discrimination Test,
    and Statistical Similarity.
    
    Parameters
    ----------
    X_real : np.ndarray
        Real attack samples.
    X_synthetic : np.ndarray
        Generated synthetic samples.
    attack_name : str
        Name of the attack type (for display).
    verbose : bool
        Print results.
    
    Returns
    -------
    report : dict
        Complete evaluation report.
    """
    report = {'attack': attack_name}
    
    # Cosine Similarity
    cos_sim = compute_cosine_similarity(X_real, X_synthetic)
    report.update(cos_sim)
    
    # MMD
    mmd_rbf = compute_mmd(X_real, X_synthetic, kernel='rbf')
    report['mmd_rbf'] = mmd_rbf
    
    # Discrimination Test
    if len(X_real) >= 20 and len(X_synthetic) >= 20:
        disc_acc = binary_discrimination_test(X_real, X_synthetic)
        report['discrimination_accuracy'] = disc_acc
    else:
        report['discrimination_accuracy'] = None
    
    # Statistical Similarity
    stats = compute_statistical_similarity(X_real, X_synthetic)
    report.update(stats)
    
    if verbose:
        print(f"\n{'─' * 50}")
        print(f"  Generation Quality Report: {attack_name}")
        print(f"{'─' * 50}")
        print(f"  Cosine Similarity (mean vectors):  {report['mean_vector_similarity']:.4f}")
        print(f"  Cosine Similarity (avg pairwise):  {report['avg_pairwise_similarity']:.4f}")
        print(f"  MMD (RBF kernel):                  {report['mmd_rbf']:.6f}")
        if report['discrimination_accuracy'] is not None:
            print(f"  Discrimination Accuracy:           {report['discrimination_accuracy']:.2%}")
            quality = "Excellent" if report['discrimination_accuracy'] < 0.55 else \
                      "Good" if report['discrimination_accuracy'] < 0.65 else \
                      "Fair" if report['discrimination_accuracy'] < 0.75 else "Poor"
            print(f"  Quality Assessment:                {quality}")
        print(f"  Mean Absolute Difference:          {report['mean_absolute_difference']:.6f}")
        print(f"  Std Absolute Difference:           {report['std_absolute_difference']:.6f}")
        print(f"{'─' * 50}")
    
    return report


